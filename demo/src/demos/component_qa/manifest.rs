//! 组件级视觉验收库存；每个条目必须有独立场景和证据。

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CaseKind {
    Widget,
    Composite,
    Provider,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ComponentVisualCase {
    pub id: &'static str,
    pub name: &'static str,
    pub category: &'static str,
    pub kind: CaseKind,
    pub states: &'static [&'static str],
}

const fn widget(
    id: &'static str,
    name: &'static str,
    category: &'static str,
    states: &'static [&'static str],
) -> ComponentVisualCase {
    ComponentVisualCase {
        id,
        name,
        category,
        kind: CaseKind::Widget,
        states,
    }
}

const fn composite(
    id: &'static str,
    name: &'static str,
    category: &'static str,
    states: &'static [&'static str],
) -> ComponentVisualCase {
    ComponentVisualCase {
        id,
        name,
        category,
        kind: CaseKind::Composite,
        states,
    }
}

const fn provider(
    id: &'static str,
    name: &'static str,
    states: &'static [&'static str],
) -> ComponentVisualCase {
    ComponentVisualCase {
        id,
        name,
        category: "Provider",
        kind: CaseKind::Provider,
        states,
    }
}

