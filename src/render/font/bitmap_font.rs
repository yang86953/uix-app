//! 5x7 bitmap font — public domain monospace font for ASCII 32..126.
//! Each character is defined as 5 bytes (one per column), bits 0-6 are rows.

use crate::api::render::TextLayoutOptions;
use crate::platform::{Point, Size};

/// A monospace bitmap font (5x7 pixels per character).
pub struct BitmapFont {
    glyphs: &'static [[u8; 5]; 95], // ASCII 32..126
}

impl BitmapFont {
    pub const fn new() -> Self {
        Self {
            glyphs: &FONT_CHARS,
        }
    }

    pub fn char_width(&self) -> f32 {
        6.0
    } // 5px + 1px spacing
    pub fn char_height(&self) -> f32 {
        9.0
    } // 7px + 2px spacing
    pub fn line_height(&self) -> f32 {
        10.0
    }

    /// Measure text size in pixels.
    pub fn measure(&self, text: &str, opts: &TextLayoutOptions) -> Size {
        if text.is_empty() {
            return Size::new(0.0, 0.0);
        }
        let cw = self.char_width();
        let lh = self.line_height();
        let max_w = if opts.max_width > 0.0 {
            opts.max_width
        } else {
            f32::MAX
        };

        if opts.word_wrap {
            let mut lines = 1u32;
            let mut line_w = 0.0f32;
            let mut max_line = 0.0f32;
            for ch in text.chars() {
                if ch == '\n' {
                    lines += 1;
                    max_line = max_line.max(line_w);
                    line_w = 0.0;
                    continue;
                }
                line_w += cw;
                if line_w > max_w {
                    lines += 1;
                    max_line = max_line.max(line_w - cw);
                    line_w = cw;
                }
            }
            max_line = max_line.max(line_w);
            Size::new(max_line.min(max_w), lines as f32 * lh)
        } else {
            let w = text.chars().filter(|&c| c != '\n').count() as f32 * cw;
            let h = (text.chars().filter(|&c| c == '\n').count() as f32 + 1.0) * lh;
            Size::new(w.min(max_w), h)
        }
    }

    /// Draw text with a specific color using the premultiplied pixel callback.
    pub fn draw_colored<F: FnMut(i32, i32, u32)>(
        &self,
        text: &str,
        pos: Point,
        color: u32,
        mut put_pixel: F,
    ) {
        let cw = self.char_width() as i32;
        let lh = self.char_height() as i32;
        let ox = pos.x as i32;
        let oy = pos.y as i32;
        let mut x = 0i32;
        let mut y = 0i32;

        for ch in text.chars() {
            if ch == '\n' {
                x = 0;
                y += lh;
                continue;
            }
            let idx = (ch as u8).wrapping_sub(32);
            if idx >= 95 {
                x += cw;
                continue;
            }
            let glyph = &self.glyphs[idx as usize];
            for (col, &byte) in glyph.iter().enumerate() {
                for row in 0..7usize {
                    if (byte >> row) & 1 != 0 {
                        put_pixel(ox + x + col as i32, oy + y + row as i32, color);
                    }
                }
            }
            x += cw;
        }
    }
}

impl Default for BitmapFont {
    fn default() -> Self {
        Self::new()
    }
}

