use crate::platform::types::KeyCode;

// ════════════════════════════════════════════════════════════════════════════
// IKeyboard — 键盘状态查询接口
// ════════════════════════════════════════════════════════════════════════════

pub trait IKeyboard {
    fn is_down(&self, key: KeyCode) -> bool;
    fn idle_ms(&self) -> u32;
    fn double_click_ms(&self) -> u32;
}

// ════════════════════════════════════════════════════════════════════════════
// ITextInput — 文本输入（IME）控制接口
// ════════════════════════════════════════════════════════════════════════════

pub trait ITextInput {
    fn start(&mut self);
    fn stop(&mut self);
}
