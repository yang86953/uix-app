//! 有类型组件的 Cargo 入口；不通过旧 XML 编译器或默认控件目录。
use super::{Builder, diagnostic, readable_tokens, validate_source};
use crate::lang::compiler::component_source::{self, NativeLibraries};
use std::path::{Path, PathBuf};

impl Builder {
    /// 检查同一来源闭包并生成真正原生 Program；不同导出写入不同文件。
    /// 输出为 OUT_DIR/uix/component/<source>.<entry_export>.rs。
    pub fn compile_component(
        &self,
        source: impl AsRef<Path>,
        entry_export: &str,
        libraries: &NativeLibraries,
    ) -> Result<PathBuf, String> {
        let source = source.as_ref();
        validate_source(source)?;
        let linked =
            component_source::link_file(&self.source_root.join(source)).map_err(diagnostic)?;
        for file in linked.source_graph.files() {
            println!("cargo::rerun-if-changed={}", file.path);
        }
        let checked = component_source::check(linked, libraries).map_err(diagnostic)?;
        // 导出名必须真实存在且由语法确认为标识符，验证后才用于生成路径。
        let tokens = component_source::emit_native(&checked, entry_export).map_err(diagnostic)?;
        let destination = self
            .output_root
            .join("uix/component")
            .join(source)
            .with_added_extension(format!("{entry_export}.rs"));
        let generated = format!(
            "// Generated by UIX component compiler; edit the .uix source.\n{}\n",
            readable_tokens(tokens)
        );
        if std::fs::read_to_string(&destination).ok().as_deref() != Some(&generated) {
            std::fs::create_dir_all(destination.parent().ok_or("UIX 生成路径没有父目录")?)
                .map_err(|error| error.to_string())?;
            std::fs::write(&destination, generated).map_err(|error| error.to_string())?;
        }
        Ok(destination)
    }
}
