// core/event.rs — 事件传播结果
//
// 框架级事件处理词汇。Widget 事件系统使用，也可用于其他事件驱动场景。
// ============================================================================

/// 事件处理结果。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EventResult {
    /// 事件已处理，不再向上冒泡。
    Handled,
    /// 事件未处理，继续冒泡。
    NotHandled,
    /// 事件已处理但允许继续冒泡（通常用于非独占型监听）。
    Bubbled,
}
